#!/usr/bin/env python3
"""Writes src/GWEPSGTable.h of the Raven code repository: sorted tables compiled into Raven of the EPSG codes of geographic
(longitude/latitude) coordinate reference systems, 2D and 3D, deprecated codes included; of those among them with a prime
meridian other than Greenwich or angles not in degrees; of the geodetic datums with a prime meridian other than Greenwich;
of the projected coordinate reference systems whose coordinates are not in metres; and of the vertical coordinate
reference systems with heights in metres and in feet.

    python3 make_epsg_geographic.py <Raven code repository>/src/GWEPSGTable.h

Development tool only: it needs pyproj (pip install pyproj), which reads the EPSG registry shipped with PROJ. Raven itself
does not need pyproj or PROJ; it reads the table written here. Run it again only to follow a newer EPSG registry, and
commit the regenerated header together with a note of the registry version (written into the header).

Raven uses the tables to classify the code of a GeoJSON "crs" member (a code in the geographic table means
longitude/latitude; a projected code that Raven has built in is compared with :InputCRS; any other code is not classified,
and the file's coordinates decide), to refuse geographic codes that are not degrees from Greenwich (also a GeoTIFF whose
geographic system is user-defined on such a datum), to refuse projected codes whose coordinates are not metres (a GeoTIFF
without ProjLinearUnitsGeoKey, a GeoJSON "crs" member), and to check the vertical code of a GeoTIFF (heights in feet are
refused, an unknown vertical code gives a warning).
"""
import sys
import pyproj
from pyproj.database import query_crs_info, get_database_metadata
from pyproj.enums import PJType

if len(sys.argv) != 2:
    sys.exit(__doc__)
from pyproj import CRS
info = query_crs_info(auth_name='EPSG', pj_types=[PJType.GEOGRAPHIC_2D_CRS, PJType.GEOGRAPHIC_3D_CRS], allow_deprecated=True)
codes = sorted(set(int(c.code) for c in info))
pm, nondeg = [], []                    # geographic codes: a prime meridian other than Greenwich; angles not in degrees
for c in codes:
    k = CRS.from_epsg(c)
    if k.prime_meridian.longitude != 0:
        pm.append((c, k.prime_meridian.name, k.prime_meridian.longitude, k.prime_meridian.unit_name))
    u = k.axis_info[0].unit_name
    if u != 'degree':
        nondeg.append((c, u))
from pyproj.database import get_codes
from pyproj.crs import Datum
dpm = []                               # geodetic datums whose prime meridian is not Greenwich
for c in sorted(int(x) for x in get_codes('EPSG', PJType.GEODETIC_REFERENCE_FRAME, allow_deprecated=True)):
    p = Datum.from_epsg(c).to_json_dict().get('prime_meridian')
    if p and p.get('name') != 'Greenwich':
        lon = p.get('longitude')
        lon, u = (lon['value'], lon['unit']['name']) if isinstance(lon, dict) else (lon, 'degree')
        dpm.append((c, p['name'], lon, u))
pinfo = query_crs_info(auth_name='EPSG', pj_types=[PJType.PROJECTED_CRS], allow_deprecated=True)
pnotm = []                             # projected systems whose coordinates are not in metres (unit of the first axis)
for c in sorted(set(int(x.code) for x in pinfo)):
    u = CRS.from_epsg(c).axis_info[0].unit_name
    if u != 'metre':
        pnotm.append((c, u))
vinfo = query_crs_info(auth_name='EPSG', pj_types=[PJType.VERTICAL_CRS], allow_deprecated=True)
vmetre, vfeet = [], []                 # vertical coordinate systems by the unit of their heights
for c in sorted(set(int(v.code) for v in vinfo)):
    u = CRS.from_epsg(c).axis_info[0].unit_name
    (vmetre.append(c) if u == 'metre' else vfeet.append((c, u)))
version = get_database_metadata('EPSG.VERSION') or 'unknown'


def ints(v):
    return '\n'.join('  ' + ','.join('%5d' % c for c in v[i:i + 14]) + (',' if i + 14 < len(v) else '') for i in range(0, len(v), 14))


def pairs(v):
    return '\n'.join('  {%5d,"%s"}%s' % (c, s, ',' if i + 1 < len(v) else '') for i, (c, s) in enumerate(v))


txt = '''/*----------------------------------------------------------------
  Raven Library Source Code
  Copyright (c) 2026 Rezgar Arabzadeh -- Raven-MODFLOW 6 groundwater coupling
  Licensed under the Artistic License 2.0 (see LICENSE)
  SPDX-License-Identifier: Artistic-2.0
  Raven-MODFLOW 6 groundwater coupling: EPSG code tables from EPSG registry %s (PROJ %s), deprecated codes included:
  - the geographic (longitude/latitude) coordinate reference systems, 2D and 3D (%d codes);
  - those of them with a prime meridian other than Greenwich (%d) and those whose angles are not in degrees (%d);
  - the geodetic datums with a prime meridian other than Greenwich (%d);
  - the projected coordinate reference systems whose coordinates are not in metres (%d);
  - the vertical coordinate reference systems with heights in metres (%d) and in feet (%d).
  Generated by tools/dev/make_epsg_geographic.py of the extra repository; do not edit by hand.
----------------------------------------------------------------*/
#ifndef GWEPSGTABLE_H
#define GWEPSGTABLE_H

struct gw_epsg_name { int code; const char *name; }; ///< a code and a name (prime meridian or unit)

static const int GW_EPSG_GEOGRAPHIC[]={
%s
};
static const int GW_EPSG_GEOGRAPHIC_N=(int)(sizeof(GW_EPSG_GEOGRAPHIC)/sizeof(GW_EPSG_GEOGRAPHIC[0]));

static const gw_epsg_name GW_EPSG_GEOG_PRIME_MERIDIAN[]={  ///< (prime meridian: name, longitude from Greenwich)
%s
};
static const int GW_EPSG_GEOG_PRIME_MERIDIAN_N=(int)(sizeof(GW_EPSG_GEOG_PRIME_MERIDIAN)/sizeof(GW_EPSG_GEOG_PRIME_MERIDIAN[0]));

static const gw_epsg_name GW_EPSG_GEOG_NOT_DEGREES[]={     ///< (angular unit)
%s
};
static const int GW_EPSG_GEOG_NOT_DEGREES_N=(int)(sizeof(GW_EPSG_GEOG_NOT_DEGREES)/sizeof(GW_EPSG_GEOG_NOT_DEGREES[0]));

static const gw_epsg_name GW_EPSG_DATUM_PRIME_MERIDIAN[]={ ///< (geodetic datum: its prime meridian, longitude from Greenwich)
%s
};
static const int GW_EPSG_DATUM_PRIME_MERIDIAN_N=(int)(sizeof(GW_EPSG_DATUM_PRIME_MERIDIAN)/sizeof(GW_EPSG_DATUM_PRIME_MERIDIAN[0]));

static const gw_epsg_name GW_EPSG_PROJECTED_NOT_METRE[]={  ///< (unit of the coordinates)
%s
};
static const int GW_EPSG_PROJECTED_NOT_METRE_N=(int)(sizeof(GW_EPSG_PROJECTED_NOT_METRE)/sizeof(GW_EPSG_PROJECTED_NOT_METRE[0]));

static const int GW_EPSG_VERTICAL_METRE[]={
%s
};
static const int GW_EPSG_VERTICAL_METRE_N=(int)(sizeof(GW_EPSG_VERTICAL_METRE)/sizeof(GW_EPSG_VERTICAL_METRE[0]));

static const gw_epsg_name GW_EPSG_VERTICAL_FEET[]={        ///< (unit of the heights)
%s
};
static const int GW_EPSG_VERTICAL_FEET_N=(int)(sizeof(GW_EPSG_VERTICAL_FEET)/sizeof(GW_EPSG_VERTICAL_FEET[0]));

#endif
''' % (version, pyproj.proj_version_str, len(codes), len(pm), len(nondeg), len(dpm), len(pnotm), len(vmetre), len(vfeet),
       ints(codes), pairs([(c, '%s, %g %s' % (n, l, u)) for c, n, l, u in pm]), pairs(nondeg),
       pairs([(c, '%s, %g %s' % (n, l, u)) for c, n, l, u in dpm]), pairs(pnotm), ints(vmetre), pairs(vfeet))
open(sys.argv[1], 'w').write(txt)
print('wrote %d geographic EPSG codes (%d in 4000-4999; %d not from Greenwich, %d not in degrees), %d datums not from Greenwich, '
      '%d projected codes not in metres and %d + %d vertical codes (metres, feet) to %s'
      % (len(codes), sum(1 for c in codes if 4000 <= c <= 4999), len(pm), len(nondeg), len(dpm), len(pnotm), len(vmetre), len(vfeet),
         sys.argv[1]))
